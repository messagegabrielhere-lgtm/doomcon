const FIXED_R = 2.4;

function radiusFor(mw) {
  if (!Number.isFinite(mw) || mw <= 0) return FIXED_R;
  return Math.min(10, 3 + 0.55 * Math.sqrt(mw));
}

// ---------------------------------------------------------------------------
// Albers Equal Area Conic, longhand.
//
//   n  = (sin φ1 + sin φ2) / 2
//   C  = cos²φ1 + 2n sin φ1
//   ρ  = √(C − 2n sin φ) / n
//   θ  = n (λ − λ0)
//   x  = ρ sin θ
//   y  = ρ0 − ρ cos θ
//
// y increases NORTHWARD in the projection and DOWNWARD in SVG, so the fitted
// transform flips it. Everything else is a scale and a translate.
// ---------------------------------------------------------------------------

const RAD = Math.PI / 180;
const PHI_1 = 29.5 * RAD;
const PHI_2 = 45.5 * RAD;
const PHI_0 = 23.0 * RAD;
const LAM_0 = -96.0 * RAD;

const ALB_N = (Math.sin(PHI_1) + Math.sin(PHI_2)) / 2;
const ALB_C = Math.cos(PHI_1) ** 2 + 2 * ALB_N * Math.sin(PHI_1);
const ALB_R0 = Math.sqrt(ALB_C - 2 * ALB_N * Math.sin(PHI_0)) / ALB_N;

/** lon/lat in WGS84 degrees -> unscaled Albers metres-ish. Pure arithmetic. */
function albers(lon, lat) {
  const rho = Math.sqrt(ALB_C - 2 * ALB_N * Math.sin(lat * RAD)) / ALB_N;
  const theta = ALB_N * (lon * RAD - LAM_0);
  return [rho * Math.sin(theta), ALB_R0 - rho * Math.cos(theta)];
}

const WIDTH = 1000;   // viewBox units; the SVG itself is width:100%
const PAD = 14;

/** Parse the outline table once and fit it to the viewBox. Deterministic. */
function frame() {
  const shapes = [];
  let minX = Infinity; let maxX = -Infinity; let minY = Infinity; let maxY = -Infinity;
  for (const ab of Object.keys(STATE_OUTLINES)) {
    const polys = STATE_OUTLINES[ab].split(';').map((poly) => poly.split(' ').map((pt) => {
      const c = pt.split(',');
      const p = albers(Number(c[0]), Number(c[1]));
      if (p[0] < minX) minX = p[0];
      if (p[0] > maxX) maxX = p[0];
      if (p[1] < minY) minY = p[1];
      if (p[1] > maxY) maxY = p[1];
      return p;
    }));
    shapes.push({ ab, polys });
  }
  const scale = (WIDTH - PAD * 2) / (maxX - minX);
  const height = Math.round(((maxY - minY) * scale + PAD * 2) * 10) / 10;
  // y grows NORTHWARD in Albers and DOWNWARD in SVG, so this flips it.
  const place = (p) => [PAD + (p[0] - minX) * scale, height - PAD - (p[1] - minY) * scale];
  const project = (lon, lat) => place(albers(lon, lat));
  // The outline was accumulated in raw projection units so the extent could be
  // measured. Now that the extent is known it moves into viewBox units, once,
  // so every consumer below works in the same coordinates the pins are in.
  for (const shape of shapes) shape.polys = shape.polys.map((poly) => poly.map(place));
  return { shapes, project, place, height, width: WIDTH };
}

const FRAME = frame();


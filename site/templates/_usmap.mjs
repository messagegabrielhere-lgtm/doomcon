// A dependency-free inline-SVG map of the United States, drawn server-side.
//
// The leading underscore marks it as a helper rather than a page: it exports no
// render(ctx). site/templates/mapPage.mjs is its only caller.
//
// ---------------------------------------------------------------------------
// WHY THERE IS NO MAPPING LIBRARY HERE
// ---------------------------------------------------------------------------
// Leaflet is 42 KB before a single tile, and a tile is a request to somebody
// else's server for a picture of the whole world when what we need is one
// country, once, at one zoom, with 1,877 dots on it. Worse, a tile map is
// CLIENT-rendered: the first paint is empty, a pre-hydration screenshot shows
// grey squares, and a crawler sees nothing at all. docs/MOTION.md Rule 0 is
// explicit that every element must already be in the static HTML before a line
// of JavaScript runs, and docs/VISITORS.md §2 A measures the cost of breaking
// that rule — the largest arriving cluster has a four-to-eight second budget on
// a phone. So: one <svg>, computed at build time, in the HTML, with no script.
//
// ---------------------------------------------------------------------------
// WHY ALBERS, AND WHY THE PROJECTION IS WRITTEN OUT LONGHAND
// ---------------------------------------------------------------------------
// Web Mercator is the default because it is what tile servers use, and it is
// the wrong projection for this argument. Mercator inflates area by 1/cos(lat):
// at 47°N (Washington, Montana, North Dakota) that is a 1.47x stretch, and at
// 26°N (the Rio Grande valley) it is 1.11x. A Mercator map of this dataset
// makes the empty northern tier look enormous and makes Texas — 235 pins, the
// second densest state on the map and the only large cluster with a live grid
// number attached — look small. Albers Equal Area Conic preserves area exactly,
// so a reader comparing two clusters by eye is comparing two true areas.
//
// Standard parallels 29.5°N and 45.5°N, origin 23°N / 96°W: the USGS values for
// the conterminous United States, unchanged since 1970, so anyone can check the
// arithmetic against a textbook. The formulae are implemented in `project()`
// below in about twelve lines of plain trigonometry.
//
// ---------------------------------------------------------------------------
// WHERE THE OUTLINE CAME FROM
// ---------------------------------------------------------------------------
// STATE_OUTLINES is the US Census Bureau's 2023 cartographic boundary file for
// states at 1:20,000,000 (`cb_2023_us_state_20m`), a public-domain federal
// dataset, reduced further with Douglas-Peucker at 0.05° and rounded to two
// decimal places — about 1.1 km, roughly a third of a pixel at the width this
// renders at. 1,752 points for 49 shapes.
//
// It is the CARTOGRAPHIC boundary, not the TIGER county boundary the collector
// geocodes against. That distinction is visible and it matters: county polygons
// extend into the Great Lakes, so a union of them draws Michigan as one blob
// with Lake Michigan filled in. The cartographic file is clipped to the
// shoreline, which is why the lakes are holes here and why the Upper Peninsula
// is a separate shape. The two files disagree about water and agree about land;
// nothing is geocoded against this one.
//
// ---------------------------------------------------------------------------
// LEGIBILITY AT 375px — THE DECISION, WRITTEN DOWN
// ---------------------------------------------------------------------------
// Measured: at 375px the content column is 343px, and the map's own aspect
// ratio puts the drawing at 343 x 216. Virginia's 407 pins would occupy about
// 22 x 16 of those pixels. That is not a dense map, it is a smudge, and a
// smudge that cannot be read is worse than a table that can — it still LOOKS
// authoritative, which is the specific failure docs/DATACENTERS.md §0 exists to
// prevent.
//
// So below 760px the map is hidden with `display:none` and the ranked state
// table takes its place. Both are in the HTML at every width; CSS chooses. The
// table is not a degraded fallback — it carries a bar per state, the status
// split, the drought category in words, and the grid, which is every channel
// the map encodes except position. Legibility wins over the picture.
//
// The same table is the images-off and screen-reader route at every width. The
// SVG carries <title> and <desc>, is role="img", and the table follows it.


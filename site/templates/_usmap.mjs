/**
 * The legend's status mark is the ACTUAL pin geometry, scaled up, not a font
 * character. site/templates/_icons.mjs is right that a bare unicode ● is
 * whatever the reader's font decides; and a legend that draws a different shape
 * from the map it labels is worse than no legend. Same code path, same shape.
 */
export function pinSwatch(status) {
  const c = 10;
  const r = 6;
  let body;
  if (status === 'operating') {
    body = `<circle cx="${c}" cy="${c}" r="${r}" fill="currentColor"/>`;
  } else if (status === 'under_construction') {
    const a = r * 1.35; const b = r * 1.2; const d = r * 0.82;
    body = `<path d="M${c} ${c - a}L${c + b} ${c + d}L${c - b} ${c + d}Z" fill="currentColor"/>`;
  } else {
    const q = r * 1.45;
    body = `<path d="M${c} ${c - q}L${c + q} ${c}L${c} ${c + q}L${c - q} ${c}Z" fill="none" stroke="currentColor" stroke-width="2"/>`;
  }
  return `<svg class="usm__pinsw" viewBox="0 0 20 20" aria-hidden="true" focusable="false">${body}</svg>`;
}


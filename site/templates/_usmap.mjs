/**
 * @param {object} dc parsed data/datacenters.json
 * @returns a render model. Pure; no clock, no randomness.
 */
export function mapModel(dc) {
  const sites = Array.isArray(dc.sites) ? dc.sites : [];
  const ri = dc.resources_index || {};
  const byCounty = ri.drought_by_county || {};
  const grids = ri.grids || {};

  const droughtOf = (site) => {
    const fips = site.county_fips || (site.resources && site.resources.drought && site.resources.drought.county_fips);
    const row = fips ? byCounty[fips] : null;
    if (!row || !row.headline || !row.headline.category) return 'nodata';
    const cat = String(row.headline.category);
    return DROUGHT_ORDER.includes(cat) ? cat : 'nodata';
  };

  const pins = [];
  const offFrame = [];
  const droughtCounts = {};
  for (const k of DROUGHT_ORDER) droughtCounts[k] = 0;
  const stateRows = new Map();
  const gridCounts = new Map();

  for (const site of sites) {
    const cat = droughtOf(site);
    droughtCounts[cat] += 1;

    const ab = site.state || null;
    if (ab) {
      if (!stateRows.has(ab)) {
        stateRows.set(ab, {
          ab,
          name: site.state_name || STATE_NAMES[ab] || ab,
          total: 0,
          operating: 0,
          under_construction: 0,
          announced: 0,
          drought: {},
          inDrought: 0,
          worst: 'nodata',
          grids: new Map(),
          capacityMw: 0,
          withCapacity: 0,
        });
        for (const k of DROUGHT_ORDER) stateRows.get(ab).drought[k] = 0;
      }
      const row = stateRows.get(ab);
      row.total += 1;
      if (STATUS_ORDER.includes(site.status)) row[site.status] += 1;
      row.drought[cat] += 1;
      if (cat !== 'none' && cat !== 'nodata') row.inDrought += 1;
      if (DROUGHT_ORDER.indexOf(cat) > DROUGHT_ORDER.indexOf(row.worst)) row.worst = cat;
      const gk = (site.resources && site.resources.grid && site.resources.grid.key) || 'UNKNOWN';
      row.grids.set(gk, (row.grids.get(gk) || 0) + 1);
      const mw = site.capacity && Number(site.capacity.it_power_mw);
      if (Number.isFinite(mw) && mw > 0) { row.capacityMw += mw; row.withCapacity += 1; }
    }

    const gk = (site.resources && site.resources.grid && site.resources.grid.key) || 'UNKNOWN';
    gridCounts.set(gk, (gridCounts.get(gk) || 0) + 1);

    if (!Number.isFinite(site.lat) || !Number.isFinite(site.lon)) continue;
    const [x, y] = FRAME.project(site.lon, site.lat);
    // Alaska, Hawaii and anything else outside the drawn frame is NOT clamped
    // to the edge — a pin drawn in the wrong place is worse than a pin listed
    // in words. It goes to offFrame and the caption says how many there are.
    if (x < 0 || x > FRAME.width || y < 0 || y > FRAME.height) {
      offFrame.push(site);
      continue;
    }
    const mw = site.capacity && Number(site.capacity.it_power_mw);
    pins.push({
      x, y, cat,
      status: STATUS_ORDER.includes(site.status) ? site.status : 'operating',
      r: radiusFor(mw),
      scaled: Number.isFinite(mw) && mw > 0,
      // Identity, carried onto the marker so a reader can ask what a dot IS.
      // A missing field stays missing all the way to the markup: a site with
      // no name renders the words "unnamed in OpenStreetMap", never a blank,
      // never a placeholder that reads like a name, and never a zero.
      name: site.name || null,
      operator: site.operator || null,
      stateAb: ab,
      grid: gk,
      confidence: site.confidence || null,
      mw: Number.isFinite(mw) && mw > 0 ? mw : null,
      sentence: site.sentence || null,
    });
  }

  // Every CONUS state gets a row, including the ones with no pins at all: a
  // state missing from the table reads as a state with no datacentres, which
  // is exactly the misreading copy.empty_state exists to head off.
  for (const ab of Object.keys(STATE_OUTLINES)) {
    if (stateRows.has(ab)) continue;
    const empty = {
      ab, name: STATE_NAMES[ab] || ab, total: 0,
      operating: 0, under_construction: 0, announced: 0,
      drought: {}, inDrought: 0, worst: 'nodata',
      grids: new Map(), capacityMw: 0, withCapacity: 0,
    };
    for (const k of DROUGHT_ORDER) empty.drought[k] = 0;
    stateRows.set(ab, empty);
  }

  const states = [...stateRows.values()].sort((a, b) => (
    b.total - a.total || a.ab.localeCompare(b.ab)
  ));

  const gaugeRows = Object.keys(ri.gauges || {}).sort().map((id) => {
    const g = ri.gauges[id];
    const pt = GAUGE_POINTS[id];
    return {
      id,
      name: g.name || id,
      cluster: g.cluster || null,
      percent_of_normal: Number.isFinite(g.percent_of_normal) ? g.percent_of_normal : null,
      reading_day: g.reading_day || null,
      reading_state: g.reading_state || 'dark',
      note: g.note || null,
      xy: pt ? FRAME.project(pt[1], pt[0]) : null,
    };
  });

  const gridRows = [...gridCounts.entries()]
    .map(([key, count]) => {
      const g = grids[key] || {};
      return {
        key,
        count,
        id: g.id || null,
        label: g.label || g.id || key,
        reading: g.reading || null,
        why: g.why_no_reading || null,
        watts_source: g.watts_source || null,
      };
    })
    .sort((a, b) => b.count - a.count || a.key.localeCompare(b.key));

  const inDrought = sites.length - droughtCounts.none - droughtCounts.nodata;
  const severe = droughtCounts.D2 + droughtCounts.D3 + droughtCounts.D4;
  const withReading = gridRows.reduce((t, g) => t + (g.reading ? g.count : 0), 0);

  return {
    pins, offFrame, states, gaugeRows, gridRows, droughtCounts,
    totals: {
      sites: sites.length,
      pinned: pins.length,
      inDrought,
      severe,
      withGridReading: withReading,
      gaugesPlotted: gaugeRows.filter((g) => g.xy).length,
      gaugesTotal: gaugeRows.length,
    },
    usdm_map_date: ri.usdm_map_date || null,
    usdm_state: ri.usdm_state || 'dark',
    usgs_reading_day: ri.usgs_reading_day || null,
    usgs_state: ri.usgs_state || 'dark',
  };
}

